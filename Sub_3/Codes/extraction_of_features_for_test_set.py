import time
from datetime import datetime
import subprocess
#Adding the time slot to check for time taken to run the job
print("\n\nFEATURE EXTRACTION FROM TEST.FASTA FILE\n\n")
start_time = time.time()
#running the job
file = input("\nEnter the file path if you have, \nElse press 'Enter' to run on defaut file:")
#running on the file
if file:
    subprocess.run(["pfeature_comp", "-i", file, "-o", "test_new_DPC.csv", "-j", "DPC"], check=True)
    
else:
    #use the provided test.fasta file
    subprocess.run(["pfeature_comp", "-i", "test_new.fasta", "-o", "test_new_DPC.csv", "-j", "DPC"], check=True)
    
print("\n\nFILES SAVED IN THE RUNNING DIRECTORY AS: test_new_DPC.csv\n\n")
#mapping the end of job
end_time = time.time()
#logging the values
log_file = open("log_file.txt","a")
log_file.write(f"Log Status on: {datetime.now().date()} at {datetime.now().time()}\n")
log_file.write(f"Total Time Taken to Extract DPCs: {(end_time - start_time):.4f}\n")
log_file.write(f"Update: Extracted DPCs for test set\n\n\n")
log_file.close()
